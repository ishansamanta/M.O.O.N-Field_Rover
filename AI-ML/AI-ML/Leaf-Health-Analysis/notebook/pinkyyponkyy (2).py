# 10. CLEAN YELLOW MASK
# ============================================================

def clean_yellow_mask(yellow_mask):

    # --------------------------------------------------------
    # Remove isolated pixels
    # --------------------------------------------------------

    open_kernel = np.ones(
        (3, 3),
        np.uint8
    )

    yellow_mask = cv2.morphologyEx(
        yellow_mask,
        cv2.MORPH_OPEN,
        open_kernel
    )


    # --------------------------------------------------------
    # Connect nearby yellow pixels
    # --------------------------------------------------------

    close_kernel = np.ones(
        (5, 5),
        np.uint8
    )

    yellow_mask = cv2.morphologyEx(
        yellow_mask,
        cv2.MORPH_CLOSE,
        close_kernel
    )


    # --------------------------------------------------------
    # Remove tiny connected components
    # --------------------------------------------------------

    num_labels, labels, stats, _ = (
        cv2.connectedComponentsWithStats(
            yellow_mask,
            connectivity=8
        )
    )

    cleaned = np.zeros_like(
        yellow_mask
    )


    for i in range(1, num_labels):

        area = stats[
            i,
            cv2.CC_STAT_AREA
        ]

        if area >= MIN_YELLOW_AREA:

            cleaned[
                labels == i
            ] = 255


    return cleaned


# ============================================================
# 11. CREATE VEGETATION COLOR CONTEXT
# ============================================================

def create_vegetation_context(
    green_mask,
    yellow_mask
):

    vegetation = cv2.bitwise_or(
        green_mask,
        yellow_mask
    )


    # --------------------------------------------------------
    # Small expansion around vegetation
    # --------------------------------------------------------

    kernel = np.ones(
        (15, 15),
        np.uint8
    )

    vegetation = cv2.dilate(
        vegetation,
        kernel,
        iterations=1
    )


    return vegetation


