# 12. GET SAM VEGETATION MASK
# ============================================================

def get_sam_vegetation_mask(frame):

    try:

        masks = mask_generator.generate(
            frame
        )

    except Exception as e:

        print(
            "SAM error:",
            e
        )

        return np.zeros(
            frame.shape[:2],
            dtype=np.uint8
        )


    vegetation_mask = np.zeros(
        frame.shape[:2],
        dtype=np.uint8
    )


    # --------------------------------------------------------
    # Get color masks
    # --------------------------------------------------------

    yellow_mask, green_mask = (
        get_color_masks(frame)
    )


    yellow_bool = (
        yellow_mask > 0
    )

    green_bool = (
        green_mask > 0
    )


    frame_area = (
        frame.shape[0] *
        frame.shape[1]
    )


    for m in masks:

        if "segmentation" not in m:
            continue


        seg = m["segmentation"]

        if seg is None:
            continue


        seg = seg.astype(bool)


        area = np.count_nonzero(
            seg
        )


        # ----------------------------------------------------
        # Ignore tiny masks
        # ----------------------------------------------------

        if area < 300:
            continue


        # ----------------------------------------------------
        # Ignore extremely large scene/background masks
        # ----------------------------------------------------

        area_ratio = (
            area /
            max(frame_area, 1)
        )

        if area_ratio > MAX_SAM_AREA_RATIO:
            continue


        # ----------------------------------------------------
        # Calculate vegetation content
        # ----------------------------------------------------

        region_green = np.count_nonzero(
            green_bool & seg
        )

        region_yellow = np.count_nonzero(
            yellow_bool & seg
        )


        vegetation_pixels = (
            region_green +
            region_yellow
        )


        vegetation_ratio = (
            vegetation_pixels /
            max(area, 1)
        )


        yellow_ratio = (
            region_yellow /
            max(area, 1)
        )


        # ----------------------------------------------------
        # Accept only vegetation-like regions
        # ----------------------------------------------------

        accept = False


        # Normal green vegetation
        if vegetation_ratio >= 0.45:

            accept = True


        # Strong yellow vegetation
        elif (
            region_yellow >= 80
            and
            yellow_ratio >= 0.20
            and
            vegetation_ratio >= 0.25
        ):

            accept = True


        if accept:

            vegetation_mask[
                seg
            ] = 255


    return vegetation_mask


