# ============================================================

def create_vegetation_context(
    green_mask,
    yellow_mask
):

    vegetation = cv2.bitwise_or(
        green_mask,
        yellow_mask
    )


    # --------------------------------------------------------
    # Small expansion around vegetation
    # --------------------------------------------------------

    kernel = np.ones(
        (15, 15),
        np.uint8
    )

    vegetation = cv2.dilate(
        vegetation,
        kernel,
        iterations=1
    )


    return vegetation


