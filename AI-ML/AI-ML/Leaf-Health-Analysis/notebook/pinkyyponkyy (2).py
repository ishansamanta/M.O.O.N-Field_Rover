def resize_frame(frame, max_dim=640):

    h, w = frame.shape[:2]

    scale = min(
        1.0,
        max_dim / max(h, w)
    )

    if scale < 1.0:

        new_w = int(w * scale)
        new_h = int(h * scale)

        frame = cv2.resize(
            frame,
            (new_w, new_h),
            interpolation=cv2.INTER_AREA
        )

    return frame


