def save_session_data(raw_data):
    try:
        parsed = json.loads(raw_data)
        records = parsed.get("records", [])
        summary = parsed.get("summary", {})

        if not records:
            print("☑️ No data records captured during session.")
            return

        # 1. Save detailed 1-second readings
        df_details = pd.DataFrame(records)
        details_path = os.path.join(DRIVE_LOG_DIR, f"{session_id}.csv")
        df_details.to_csv(details_path, index=False)

        # 2. Save session summary
        summary_path = os.path.join(DRIVE_LOG_DIR, f"{session_id}_summary.csv")
        df_summary = pd.DataFrame([summary])
        df_summary.to_csv(summary_path, index=False)

        print(f"\n💾 Diagnostic log and summary successfully written to Drive:")
        print(f"   - Details: {details_path}")
        print(f"   - Summary: {summary_path}")

        # Confirm success back to JS
        output.eval_js("console.log('Successfully saved logs to Google Drive.');")
    except Exception as e:
        print(f"❌ Error writing to Google Drive: {str(e)}")

output.register_callback('notebook.save_session_data', save_session_data)

