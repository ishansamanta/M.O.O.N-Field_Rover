def get_color_masks(frame):

    hsv = cv2.cvtColor(
        frame,
        cv2.COLOR_BGR2HSV
    )


    # --------------------------------------------------------
    # YELLOW
    # --------------------------------------------------------

    yellow_mask = (
        (hsv[:, :, 0] >= YELLOW_H_LOW) &
        (hsv[:, :, 0] <= YELLOW_H_HIGH) &
        (hsv[:, :, 1] >= YELLOW_S_MIN) &
        (hsv[:, :, 2] >= YELLOW_V_MIN)
    )

    yellow_mask = (
        yellow_mask.astype(np.uint8) * 255
    )


    # --------------------------------------------------------
    # GREEN
    # --------------------------------------------------------

    green_mask = (
        (hsv[:, :, 0] >= GREEN_H_LOW) &
        (hsv[:, :, 0] <= GREEN_H_HIGH) &
        (hsv[:, :, 1] >= GREEN_S_MIN) &
        (hsv[:, :, 2] >= GREEN_V_MIN)
    )

    green_mask = (
        green_mask.astype(np.uint8) * 255
    )


    return yellow_mask, green_mask


